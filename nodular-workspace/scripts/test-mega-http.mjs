import assert from 'node:assert/strict'
const base = process.env.BASE || 'http://localhost:3001'
const send = (path, body) => fetch(base + path, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })
const health = await (await fetch(base + '/api/mega/health')).json()
assert(health.unavailable.includes('Hypit video cloning'))
assert.equal(health.whisper.configured, false)
const invalid = await send('/api/mega/run', { transcript: 'short', audience: 'bakers' })
assert.equal(invalid.status, 400)
const input = { transcript: 'A bakery wants to test a reviewed pickup order checklist using permitted sample data. No validated earnings claims.', audience: 'independent bakeries', variants: 100 }
const response = await send('/api/mega/run', input)
assert.equal(response.status, 200)
const pack = await response.json()
assert.equal(pack.status, 'draft')
assert.equal(pack.cards.length, 10)
assert.equal(pack.variants.length, 100)
const image = await fetch(base + pack.cards[0].url)
assert.equal(image.status, 200)
assert.equal(image.headers.get('content-type'), 'image/png')
assert.equal(image.headers.get('cache-control'), 'private, no-store')
const bytes = Buffer.from(await image.arrayBuffer())
assert.equal(bytes.readUInt32BE(16), 1080)
assert.equal(bytes.readUInt32BE(20), 1920)
assert.equal((await fetch(base + `/api/mega/packs/${pack.id}/cards/100`)).status, 404)
assert.equal((await fetch(base + '/api/mega/packs/not-owned')).status, 404)
const queued = await (await send(`/api/mega/packs/${pack.id}/render`, {})).json()
const thread = await (await fetch(base + `/api/agent/threads/${queued.threadId}`)).json()
assert.equal(thread.run.status, 'awaiting_approval')
assert.equal(thread.approvals[0].tool, 'mega_render_video')
assert.deepEqual(thread.approvals[0].args, { id: pack.id })
const denied = await send(`/api/agent/approvals/${queued.approvalId}`, { approve: false })
assert.equal(denied.status, 200)
const stillDraft = await (await fetch(base + `/api/mega/packs/${pack.id}`)).json()
assert.equal(stillDraft.render, undefined)
assert.equal((await send('/api/mega/run', { ...input, useAi: true })).status, 400)
const failed = await send('/api/mega/run', { ...input, useAi: true, allowModel: true })
assert.equal(failed.status, 400)
assert.match((await failed.json()).error, /real model/)
const history = await (await fetch(base + '/api/mega/packs')).json()
assert(history.some((item) => item.id === pack.id && item.status === 'draft'))
assert(history.some((item) => item.status === 'failed' && /real model/.test(item.error)))
console.log('PASS HTTP native PNG/100-combination pack, owner-checked downloads, visible errors/history, exact render approval and rejection without execution')
